import { RENDER_REQUEST_LOCAL, type RenderPages } from './renderRequest.ts';

const RUNTIME = '@storybook-astro/framework/server-app';

/**
 * Renders one node of a story tree; recursive through `Astro.self`.
 *
 * A story's slot names are only known at render time, and a template can't
 * pass a slot under a computed name, so a component node is rendered through
 * Astro's own `renderComponent` with a slots object, the way Astro renders a
 * component it compiled. `$$result` is the render context Astro's compiler
 * gives every component's frontmatter.
 */
export function storyNodeSource() {
  return `---
// Generated by @storybook-astro/framework. Renders a story tree: HTML, a list
// of nodes, or a component with its props and named slots.
import { renderComponent, renderTemplate } from 'astro/runtime/server/index.js';

const { node } = Astro.props;
let component;

if (node && typeof node === 'object' && !Array.isArray(node)) {
  const slots = Object.fromEntries(
    Object.entries(node.slots).map(([name, child]) => [
      name,
      () => renderTemplate\`\${renderComponent($$result, 'StoryNode', Astro.self, { node: child })}\`
    ])
  );

  component = renderComponent($$result, 'StoryComponent', node.Component, node.props, slots);
}
---
{typeof node === 'string' && <Fragment set:html={node} />}
{Array.isArray(node) && node.map((child) => <Astro.self node={child} />)}
{component}
`;
}

/**
 * A render page for the stories of one story file. It imports only the
 * components that file (and the preview) uses, so Astro attaches only their
 * styles and islands to the response.
 */
export function renderPageSource(options: {
  /** Import specifiers relative to the page, keyed by the module id the browser sends. */
  components: Record<string, string>;
  storyNodeImport: string;
}) {
  const entries = Object.entries(options.components);

  return `---
// Generated by @storybook-astro/framework.
import { resolveStoryTree } from '${RUNTIME}';
import { maybeRenderHead } from 'astro/runtime/server/index.js';
import sanitization from 'virtual:storybook-astro/sanitize-config';
import StoryNode from ${JSON.stringify(options.storyNodeImport)};
${entries.map(([, specifier], index) => `import Component${index} from ${JSON.stringify(specifier)};`).join('\n')}

export const prerender = false;

const components = {
${entries.map(([moduleId], index) => `  ${JSON.stringify(moduleId)}: Component${index},`).join('\n')}
};

// Set by the render API before it rewrites to this page. Requested directly,
// without the API's auth and story rules, the page doesn't exist.
const renderRequest = Astro.locals[${JSON.stringify(RENDER_REQUEST_LOCAL)}];

if (!renderRequest) {
  return new Response(null, { status: 404 });
}

let tree;

try {
  tree = await resolveStoryTree(renderRequest, components, sanitization);
} catch (error) {
  return new Response(error instanceof Error ? error.message : String(error), { status: 500 });
}
---
{/* The page has no <head>: Astro writes a page's styles where its first
    element starts, and a story that is only an island has none. */}
{maybeRenderHead()}
<StoryNode node={tree} />
`;
}

/** The `/api` endpoint: the Hono render API from the framework. */
export function apiRouteSource(renderPages: RenderPages) {
  return `// Generated by @storybook-astro/framework.
import { createRenderApi } from '${RUNTIME}';

export const prerender = false;

const app = createRenderApi(${JSON.stringify(renderPages, null, 2)});

export const ALL = (context) => app.fetch(context.request, context);
`;
}
