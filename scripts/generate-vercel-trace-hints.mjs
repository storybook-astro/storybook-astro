// Generates api/storybook-astro/_vercel-trace-hints.js for a server-mode
// integration app (run from the app directory, after `storybook build`).
//
// Why this exists: the deployed render server boots a Vite SSR server that
// resolves packages at runtime (probing package.json exports/browser/module
// entries), but Vercel's file tracer only ships the exact files reachable
// from static imports — and its `includeFiles` option silently ignores any
// node_modules path. The result is half-shipped packages and
// "Failed to resolve entry for package …" errors in production. This script
// closes the gap by emitting a never-executed module that references every
// runtime file of the packages Vite resolves dynamically, so the tracer
// ships them completely, at their real node_modules paths.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';

// Packages the render server resolves through Vite at request time. Their
// static-import dependency trees are traced from here too, so transitive
// packages don't need listing.
const VITE_RESOLVED_PACKAGES = [
  // astro wholesale: the runtime reads untraceable files all over the package
  // (tsconfigs/*.json via tsconfig `extends`, runtime templates, …).
  'astro',
  '@astrojs/compiler',
  'preact',
  'preact-render-to-string',
  '@astrojs/preact',
  'msw'
];

const RUNTIME_FILE_RE = /\.(?:m?js|cjs|json|node|css|wasm)$/;

const appDir = process.cwd();
const outputFile = resolve(appDir, 'api/storybook-astro/_vercel-trace-hints.js');
const requireFromApp = createRequire(join(appDir, 'package.json'));

function resolvePackageDir(packageName) {
  try {
    // Fails for packages whose exports map hides ./package.json.
    return dirname(requireFromApp.resolve(`${packageName}/package.json`));
  } catch {
    let dir = dirname(requireFromApp.resolve(packageName));

    while (dir !== dirname(dir)) {
      const manifest = join(dir, 'package.json');

      if (existsSync(manifest) && JSON.parse(readFileSync(manifest, 'utf-8')).name === packageName) {
        return dir;
      }

      dir = dirname(dir);
    }

    throw new Error(`Could not locate package directory for ${packageName}`);
  }
}

function listRuntimeFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = join(dir, entry.name);

    if (entry.isDirectory()) {
      return entry.name === 'node_modules' ? [] : listRuntimeFiles(fullPath);
    }

    return RUNTIME_FILE_RE.test(entry.name) ? [fullPath] : [];
  });
}

const lines = [
  '/* AUTO-GENERATED by scripts/generate-vercel-trace-hints.mjs — do not edit.',
  '   Never executed; exists so Vercel\'s file tracer ships complete packages',
  '   that the render server resolves through Vite at runtime. */',
  'export async function __vercelTraceHints() {'
];

for (const packageName of VITE_RESOLVED_PACKAGES) {
  const packageDir = resolvePackageDir(packageName);
  const files = listRuntimeFiles(packageDir);

  lines.push(`  // ${packageName} (${files.length} files)`);

  for (const file of files) {
    const specifier = relative(dirname(outputFile), file).replace(/\\/g, '/');

    lines.push(`  await import(${JSON.stringify(specifier)});`);
  }
}

lines.push('}', '');

writeFileSync(outputFile, lines.join('\n'));
console.log(
  `[trace-hints] wrote ${outputFile} (${lines.length - 6} file references)`
);
